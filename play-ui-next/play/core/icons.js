/** Returns an <svg> icon. Unknown names render an empty glyph rather than throwing. */
export function icon(name, className = '') {
  const svg = document.createElementNS(ns, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  const filled = Object.hasOwn(fill, name);
  svg.setAttribute('class', `i ${filled ? 'i-fill' : 'i-line'} ${className}`.trim());
  const path = document.createElementNS(ns, 'path');
  path.setAttribute('d', filled ? fill[name] : stroke[name] ?? '');
  svg.append(path);
  return svg;
}

