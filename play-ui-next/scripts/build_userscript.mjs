// Builds the Safari Userscripts version of DLook Next:
//   node play-ui-next/scripts/build_userscript.mjs            → play-ui-next/dist/DLook-Safari.user.js
//   node play-ui-next/scripts/build_userscript.mjs --release  → also exports/<version>/ (script + meta)
//
// play.dlsite.com: the ES-module app (play/userscript.js and everything it imports, including
// the lazily imported views) is bundled into one IIFE with Vite/Rollup; its CSS files and the
// logo are inlined, because Userscripts can neither import modules nor load extension files.
// DLsite store pages: the price-badge scripts are concatenated exactly like the original
// build (scripts/build_userscript.mjs), using userscripts/safari-platform.js.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const here = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, here), 'utf8');
const manifest = JSON.parse(await read('manifest.json'));
const [store] = manifest.content_scripts;
const matches = [...new Set(manifest.content_scripts.flatMap(entry => entry.matches))];
const releaseUrl = 'https://github.com/CbShuiMu/DLook/releases/latest/download/';
const scriptName = 'DLook-Safari.user.js';
const metadataName = 'DLook-Safari.meta.js';

/* ---------------- bundle the play app */
const bundle = await build({
  configFile: false,
  logLevel: 'warn',
  root: fileURLToPath(new URL('play/', here)),
  build: {
    write: false,
    minify: false,
    target: 'safari16',
    lib: { entry: fileURLToPath(new URL('play/userscript.js', here)), name: 'DLookNext', formats: ['iife'] },
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});
const chunk = [bundle].flat().flatMap(result => result.output).find(item => item.type === 'chunk');
if (!chunk) throw new Error('Bundling produced no output');

const styleNames = (await readdir(new URL('play/styles/', here))).filter(name => name.endsWith('.css') && name !== 'host.css');
const styles = Object.fromEntries(await Promise.all(styleNames.map(async name => [name, (await read(`play/styles/${name}`)).trim()])));
const hostCss = (await read('play/styles/host.css')).trim();
const logo = `data:image/svg+xml;charset=utf-8,${encodeURIComponent((await read('dlook-logo.svg')).trim())}`;

/* ---------------- store pages (unchanged price badges) */
const [platform, sources, cardCss, layoutCss, rawLogo] = await Promise.all([
  readFile(new URL('../../userscripts/safari-platform.js', import.meta.url), 'utf8'),
  Promise.all(store.js.filter(name => name !== 'platform.js').map(read)),
  read('badge.css'),
  read('badge-layout.css'),
  read('dlook-logo.svg'),
]);
const inlineLogo = rawLogo
  .replace(/<style>[\s\S]*?<\/style>/, '')
  .replaceAll('class="dlook-logo-blue"', 'fill="#bbdfff"')
  .replaceAll('class="dlook-logo-gold"', 'fill="#ffd25d"');

const metadata = [
  '// ==UserScript==',
  '// @name         DLook — DLsite 史低价',
  '// @namespace    https://dlook.site/',
  '// @description  在 DLsite 显示 DLook 价格信息，并为 DLsite Play 提供全新的玻璃风格界面、播放器和漫画阅读器。',
  '// @version      ' + manifest.version,
  '// @updateURL    ' + releaseUrl + metadataName,
  '// @downloadURL  ' + releaseUrl + scriptName,
  ...matches.map(match => '// @match        ' + match),
  '// @run-at       document-start',
  '// @inject-into  content',
  '// @noframes',
  '// @grant        GM.xmlHttpRequest',
  '// ==/UserScript==',
];

const source = [
  ...metadata,
  '',
  '// Generated by node play-ui-next/scripts/build_userscript.mjs — do not edit by hand.',
  '(() => {',
  "  'use strict';",
  '',
  "if (location.hostname === 'play.dlsite.com') {",
  chunk.code.trim(),
  '  const startPlay = () => DLookNext.run({',
  '    version: ' + JSON.stringify(manifest.version) + ',',
  '    logo: ' + JSON.stringify(logo) + ',',
  '    hostCss: ' + JSON.stringify(hostCss) + ',',
  '    styles: ' + JSON.stringify(styles) + ',',
  '  });',
  '  // At document-start Safari may not have created <html> yet.',
  '  if (document.documentElement) startPlay();',
  '  else {',
  '    const rootObserver = new MutationObserver(() => {',
  '      if (!document.documentElement) return;',
  '      rootObserver.disconnect();',
  '      startPlay();',
  '    });',
  '    rootObserver.observe(document, { childList: true });',
  '  }',
  '  return;',
  '}',
  '',
  platform.trim(),
  '',
  'const dlookCardCss = ' + JSON.stringify(cardCss.trim()) + ';',
  'const dlookLayoutCss = ' + JSON.stringify(layoutCss.trim()) + ';',
  'const dlookLogoMarkup = ' + JSON.stringify(inlineLogo.trim()) + ';',
  '',
  'function startStore() {',
  sources.map(code => code.trim()).join('\n\n'),
  '}',
  "if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', startStore, { once: true });",
  'else startStore();',
  '})();',
  '',
].join('\n');

async function writeIfChanged(path, content) {
  const existing = await readFile(path, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; });
  if (existing !== content) await writeFile(path, content);
}

const dist = new URL('dist/', here);
await mkdir(dist, { recursive: true });
await writeIfChanged(new URL(scriptName, dist), source);
console.log(`DLook Next Userscript: play-ui-next/dist/${scriptName} (${(source.length / 1024).toFixed(0)} KB)`);

if (process.argv.includes('--release')) {
  const directory = new URL('../../exports/' + manifest.version + '/', import.meta.url);
  await mkdir(directory, { recursive: true });
  await Promise.all([
    writeIfChanged(new URL(scriptName, directory), source),
    writeIfChanged(new URL(metadataName, directory), metadata.join('\n') + '\n'),
  ]);
  console.log('Safari release assets: exports/' + manifest.version + '/');
}
