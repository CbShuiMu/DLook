import { mkdir, readFile, writeFile } from 'node:fs/promises';

const extension = new URL('../chrome-extension/', import.meta.url);
const read = name => readFile(new URL(name, extension), 'utf8');
const manifest = JSON.parse(await read('manifest.json'));
const [store, play] = manifest.content_scripts;
const matches = [...new Set(manifest.content_scripts.flatMap(entry => entry.matches))];
const output = new URL('../public/dlook.user.js', import.meta.url);
const releaseUrl = 'https://github.com/CbShuiMu/DLook/releases/latest/download/';
const scriptName = 'DLook-Safari.user.js';
const metadataName = 'DLook-Safari.meta.js';

const [platform, sources, cardCss, layoutCss, logo, playSources, playCss] = await Promise.all([
  readFile(new URL('../userscripts/safari-platform.js', import.meta.url), 'utf8'),
  Promise.all(store.js.filter(name => name !== 'platform.js').map(read)),
  read('badge.css'),
  read('badge-layout.css'),
  read('dlook-logo.svg'),
  Promise.all(play.js.map(read)),
  Promise.all(play.css.map(read)),
]);
const metadata = [
  '// ==UserScript==',
  '// @name         DLook — DLsite 史低价',
  '// @namespace    https://dlook.site/',
  '// @description  在 DLsite 显示 DLook 价格信息，并为 DLsite Play 提供底部导航。',
  '// @version      ' + manifest.version,
  '// @updateURL    ' + releaseUrl + metadataName,
  '// @downloadURL  ' + releaseUrl + scriptName,
  ...matches.map(match => '// @match        ' + match),
  '// @run-at       ' + play.run_at.replaceAll('_', '-'),
  '// @inject-into  content',
  '// @noframes',
  '// @grant        GM.xmlHttpRequest',
  '// ==/UserScript==',
];
const inlineLogo = logo
  .replace(/<style>[\s\S]*?<\/style>/, '')
  .replaceAll('class="dlook-logo-blue"', 'fill="#bbdfff"')
  .replaceAll('class="dlook-logo-gold"', 'fill="#ffd25d"');
const source = [
  ...metadata,
  '',
  '// Generated by npm run build:userscript.',
  '(() => {',
  "  'use strict';",
  '',
  platform.trim(),
  '',
  "if (location.hostname === 'play.dlsite.com') {",
  '  function startPlay() {',
  '  applyStyles(document.head ?? document.documentElement, undefined, ' + JSON.stringify(playCss.map(css => css.trim()).join('\n\n')) + ');',
  playSources.map(code => code.trim()).join('\n\n'),
  '  }',
  '  if (document.documentElement) startPlay();',
  '  else {',
  '    const rootObserver = new MutationObserver(() => {',
  '      if (!document.documentElement) return;',
  '      rootObserver.disconnect();',
  '      startPlay();',
  '    });',
  '    rootObserver.observe(document, { childList: true });',
  '  }',
  '  return;',
  '}',
  '',
  'const dlookCardCss = ' + JSON.stringify(cardCss.trim()) + ';',
  'const dlookLayoutCss = ' + JSON.stringify(layoutCss.trim()) + ';',
  'const dlookLogoMarkup = ' + JSON.stringify(inlineLogo.trim()) + ';',
  '',
  'function startStore() {',
  sources.map(code => code.trim()).join('\n\n'),
  '}',
  "if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', startStore, { once: true });",
  'else startStore();',
  '})();',
  '',
].join('\n');

async function writeIfChanged(path, content) {
  const existing = await readFile(path, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
  });
  if (existing !== content) await writeFile(path, content);
}

await writeIfChanged(output, source);
console.log('DLook Userscripts: public/dlook.user.js');

if (process.argv.includes('--release')) {
  const directory = new URL('../exports/' + manifest.version + '/', import.meta.url);
  await mkdir(directory, { recursive: true });
  await Promise.all([
    writeIfChanged(new URL(scriptName, directory), source),
    writeIfChanged(new URL(metadataName, directory), metadata.join('\n') + '\n'),
  ]);
  console.log('Safari Release assets: exports/' + manifest.version + '/');
}
